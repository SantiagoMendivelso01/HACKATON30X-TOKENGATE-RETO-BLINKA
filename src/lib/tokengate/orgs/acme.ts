const channels: Channel[] = ["pdf", "email"];

const invoice = (
  [n, supplier, agentId, category, amount, due, description, conf, missing]: Seed,
  i: number,
): Invoice => {
  const issue = new Date(due + "T00:00:00Z");
  issue.setUTCDate(issue.getUTCDate() - 14);
  return {
    id: `inv-${n}`,
    kind: "invoice",
    reference: `INV-2026-${n}`,
    supplier,
    agentId,
    category,
    amount,
    dueDate: `${due}T00:00:00Z`,
    issueDate: issue.toISOString(),
    receivedAt: issue.toISOString(),
    channel: channels[i % 2]!,
    description,
    extractionConfidence: conf,
    missingFields: missing ?? [],
  };
};

